// Turn drizzle-kit's introspected crawl schema into the committed artifact
// bff/src/db/schema/crawl.generated.ts, behind a do-not-edit banner
// (ADR-0021 §2). Run by `make drizzle-pull` after `drizzle-kit introspect`.
//
// Deterministic when crawl has no tables (the case until BUILD_PLAN 1.1):
// whatever introspect did or did not produce, the artifact is the banner
// plus an honest "no tables yet" note — never a stale copy, never missing.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", ".crawl-introspect", "schema.ts");
const DST = join(HERE, "..", "src", "db", "schema", "crawl.generated.ts");

const BANNER = [
  "// GENERATED by `make drizzle-pull` — DO NOT EDIT (ADR-0021 §2).",
  "// Introspected from the live crawl schema, which Alembic owns. Hand",
  "// edits are overwritten, and `make check` fails on the diff either way.",
  "",
].join("\n");

const introspected = existsSync(SRC) ? readFileSync(SRC, "utf8") : "";
const hasTables = /pgTable|pgEnum|pgView/.test(introspected);

const body = hasTables
  ? introspected
  : "// crawl has no tables yet — the first arrives with BUILD_PLAN 1.1.\n";

writeFileSync(DST, `${BANNER}${body}`);
console.log(
  hasTables
    ? `·  crawl.generated.ts written from introspected crawl tables`
    : `·  crawl.generated.ts written empty (crawl has no tables until BUILD_PLAN 1.1)`,
);
